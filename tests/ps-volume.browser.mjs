import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { createContext, runInContext } from 'node:vm';
import { chromium } from 'playwright';

const origin = process.env.PS_PREVIEW_ORIGIN || 'http://localhost:5173';
test('PS dashboard navigation, real workbook, date controls, updates, access and mobile layout', async () => {
  const bytes = await fs.readFile('data/dashboard-sources/PS Volume Data.xlsx');
  const readerContext = createContext({ Uint8Array, ArrayBuffer, TextDecoder, TextEncoder });
  runInContext(await fs.readFile('apps/frontend/public/vendor/xlsx.js', 'utf8'), readerContext);
  const excel = readerContext.XLSX;
  const workbook = excel.read(new Uint8Array(bytes), { type: 'array' });
  const grid = excel.utils.sheet_to_json(workbook.Sheets.Data, { header: 1, raw: true });
  const indexes = Object.fromEntries(grid[0].map((name, index) => [name, index]));
  const seen = new Set();
  const records = grid.slice(1).filter(row => { const no = row[indexes.No]; if (no == null || seen.has(String(no))) return false; seen.add(String(no)); return true; });
  const expected202 = records.filter(row => ['HB', 'CO'].includes(row[indexes['From Store']])).length;
  const expectedA005 = records.filter(row => row[indexes['From Store']] === 'A005').length;
  const expectedTotal = expected202 + expectedA005;
  const format = n => n.toLocaleString('en-GB');
  const dateOf = row => { const date = excel.SSF.parse_date_code(row[indexes['Issued At']]); return date.y + '-' + String(date.m).padStart(2, '0') + '-' + String(date.d).padStart(2, '0'); };
  const dates = records.map(dateOf).sort();
  const minDate = dates[0], maxDate = dates.at(-1);
  const expectedDays = Math.min(31, Math.round((Date.parse(maxDate) - Date.parse(minDate)) / 86400000) + 1);
  const browser = await chromium.launch({ headless: true });
  const errors = [];
  let updatedAt = '2026-11-02T19:00:00Z', fileRequests = 0, unavailable = false;
  const permissions = { amos: true, aog: true, fak: true, marshaling: true, permits: true, psvolume: true };
  const context = await browser.newContext({ viewport: { width: 1500, height: 1100 } });
  await context.route('**/api/me', route => route.fulfill({ json: { id: 'preview', name: 'Preview', role: 'admin', canExport: true, permissions } }));
  await context.route('**/api/dashboard-sync/psvolume/metadata*', route => route.fulfill({ status: unavailable ? 503 : 200, json: unavailable ? { error: 'Unavailable' } : { metadata: { fileName: 'PS Volume Data.xlsx', updatedAt } } }));
  await context.route('**/api/dashboard-sync/psvolume/file*', route => { fileRequests++; return route.fulfill({ body: bytes, contentType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' }); });
  const page = await context.newPage(); page.on('pageerror', error => errors.push(error.message));
  try {
    await page.goto(origin + '/portal');
    await page.locator('.department-card').first().waitFor();
    assert.equal(await page.locator('.department-card').count(), 6);
    await page.getByRole('link', { name: /PS Volume Analysis/ }).click();
    await page.getByTestId('ps-kpi-2').waitFor();
    assert.equal(await page.getByTestId('ps-kpi-0').innerText(), format(expected202));
    assert.equal(await page.getByTestId('ps-kpi-1').innerText(), format(expectedA005));
    assert.equal(await page.getByTestId('ps-kpi-2').innerText(), format(expectedTotal));
    assert.equal(await page.getByTestId('ps-kpi-3').innerText(), (expectedA005 / expectedTotal * 100).toFixed(2) + '%');
    assert.equal(await page.locator('#ps-from').inputValue(), minDate);
    assert.equal(await page.locator('#ps-to').inputValue(), maxDate);
    assert.equal(await page.locator('.ps-trend circle').count(), expectedDays * 2);
    assert.equal(await page.locator('tbody tr').count(), new Set(records.map(row => String(row[indexes['Drop Area']]).trim())).size);
    assert.ok((await page.locator('tfoot').innerText()).includes(format(expectedTotal)));
    assert.equal(await page.locator('.ps-point-label').count(), expectedDays * 2);
    const placement = await page.evaluate(() => { const table = document.querySelector('.ps-distribution').getBoundingClientRect(); const charts = document.querySelector('.ps-comparisons').getBoundingClientRect(); return { sameRow: Math.abs(table.top - charts.top) < 2, right: table.left >= charts.right }; });
    assert.ok(placement.sameRow && placement.right, 'destination table must sit beside comparisons on desktop');
    await fs.mkdir('artifacts', { recursive: true });
    await page.screenshot({ path: 'artifacts/ps-volume-desktop.png', fullPage: true });
    await page.locator('#ps-from').fill(maxDate);
    await page.locator('#ps-to').fill(maxDate);
    assert.equal(await page.locator('.ps-trend circle').count(), 2);
    const dayTotal = await page.getByTestId('ps-kpi-2').innerText();
    assert.notEqual(dayTotal, format(expectedTotal));
    updatedAt = '2026-11-02T19:01:00Z';
    await page.getByRole('button', { name: 'Refresh data', exact: true }).click();
    await page.getByRole('button', { name: 'Refresh data', exact: true }).waitFor();
    assert.equal(await page.locator('#ps-from').inputValue(), maxDate);
    assert.equal(await page.getByTestId('ps-kpi-2').innerText(), dayTotal);
    assert.equal(fileRequests, 2);
    await page.getByRole('button', { name: 'Refresh data', exact: true }).click();
    await page.getByRole('button', { name: 'Refresh data', exact: true }).waitFor();
    assert.equal(fileRequests, 2, 'unchanged metadata must not download the file again');
    await page.getByRole('button', { name: 'Export for PowerPoint' }).click();
    const fullPeriod = page.getByRole('button', { name: 'Full available period' });
    await fullPeriod.waitFor();
    await page.waitForFunction(() => !document.querySelector('.export-available-period button')?.disabled);
    await fullPeriod.click();
    const exportRequestCount = fileRequests;
    const downloadPromise = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Generate PowerPoint Images' }).click();
    const download = await downloadPromise;
    assert.equal(download.suggestedFilename(), `PS_Volume_Analysis_${minDate}_${maxDate}.png`);
    await download.saveAs('artifacts/ps-volume-export-4k.png');
    const png = await fs.readFile('artifacts/ps-volume-export-4k.png');
    assert.equal(png.subarray(1, 4).toString(), 'PNG');
    assert.equal(png.readUInt32BE(16), 3840); assert.equal(png.readUInt32BE(20), 2160);
    assert.ok(png.length > 50000, 'export must contain rendered report content');
    assert.equal(fileRequests, exportRequestCount + 1, 'export must fetch a fresh workbook');
    assert.equal(await page.locator('#ps-from').inputValue(), maxDate, 'export does not change live filters');
    await page.getByRole('button', { name: 'Close', exact: true }).click();
    const requestsAfterExport = fileRequests;
    unavailable = true;
    await page.getByRole('button', { name: 'Refresh data', exact: true }).click();
    await page.getByRole('alert').waitFor();
    assert.equal(await page.getByTestId('ps-kpi-2').innerText(), dayTotal);
    unavailable = false;
    await page.getByRole('button', { name: 'Retry', exact: true }).click();
    await page.getByRole('button', { name: 'Refresh data', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Reset to full period' }).click();
    assert.equal(await page.getByTestId('ps-kpi-2').innerText(), format(expectedTotal));
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: 'artifacts/ps-volume-mobile.png', fullPage: true });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'mobile page must not overflow horizontally');
    assert.deepEqual(errors, []);
    permissions.psvolume = false;
    await page.reload();
    await page.getByRole('alert').waitFor();
    assert.match(await page.getByRole('alert').innerText(), /Access restricted/);
    assert.equal(fileRequests, requestsAfterExport);
  } finally { await context.close(); await browser.close(); }
});
